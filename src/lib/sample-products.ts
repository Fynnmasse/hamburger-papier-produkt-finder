/**
 * Extract the referencedId from a product's shop URL.
 * Product URLs are in the format: https://www.hamburgpapier-shop.de/detail/{referencedId}
 */
export function getReferencedId(productUrl: string): string | null {
  const match = productUrl.match(/\/detail\/([a-f0-9]+)$/);
  return match ? match[1] : null;
}

/**
 * Check if a product supports the free sample feature.
 */
export function hasSampleSupport(productUrl: string): boolean {
  const id = getReferencedId(productUrl);
  return id !== null && sampleProductIds.has(id);
}
